#!/usr/bin/env bash
#
# Vendoring the platform and the profile into a machine: replacing the symlinks
# with real copies and recording which version the machine uses.
#
# Why a copy rather than a symlink or a submodule. A machine's repository has
# to be self-contained: one `clone` and everything works, with no access to a
# second repository, no `--recursive`, no forgotten pointer commit. Machines go
# out to clients, and giving a client access to the platform repository just so
# their config builds is a poor trade.
#
# The price of a copy: you cannot tell at a glance whether someone edited the
# platform in place. So .vendor.lock is written alongside it with the version
# and checksums, and platform/bin/check-vendor.sh compares them. A platform
# that has silently drifted otherwise looks perfectly healthy.
#
#   ./bin/vendor.sh <machine-path>            # place copies of platform and profile
#   ./bin/vendor.sh <machine-path> --dry-run  # show what would change
#   ./bin/vendor.sh <machine-path> --unlink   # remove the copies

set -euo pipefail

ROOT="$( cd -P "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )"

# Needed for sha256_file: a bare `shasum` may not be available.
# shellcheck source=platform/lib/lib-env.sh
. "$ROOT/platform/lib/lib-env.sh"
MACHINE=""; DRY=0; UNLINK=0

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1; shift ;;
    --unlink)  UNLINK=1; shift ;;
    -*) echo "Unknown argument: $1" >&2; exit 2 ;;
    *)  MACHINE="$1"; shift ;;
  esac
done
[ -n "$MACHINE" ] || { echo "Usage: $0 <machine-path> [--dry-run|--unlink]" >&2; exit 2; }

# A path rather than a name: machines live outside this repository.
DEST="$MACHINE"
[ -d "$DEST" ] || { echo "Error: no directory '$DEST'" >&2; exit 2; }

run() { if [ "$DRY" -eq 1 ]; then printf '  [dry] %s\n' "$*"; else "$@"; fi; }

if [ "$UNLINK" -eq 1 ]; then
  for layer in platform profile; do
    run rm -rf "$DEST/$layer"
  done
  run rm -f "$DEST/.vendor.lock"
  echo "Copies removed from '$DEST'. ./bootstrap will bring the platform back."
  exit 0
fi

# Checksums are computed FROM THE SOURCE and over relative paths: absolute ones
# depend on where the workspace lives, and the lock would stop matching on
# another machine — that is, the check would break exactly where it is
# needed.
manifest() {
  local dir="$1" prefix="$2"
  ( cd "$dir" && find . -type f -not -name '.DS_Store' | sort \
      | while IFS= read -r f; do printf '%s  %s/%s\n' "$(sha256_file "$f")" "$prefix" "${f#./}"; done )
}

echo "== vendoring into $DEST"
for layer in platform profile; do
  src="$ROOT/platform"; [ "$layer" = profile ] && src="$ROOT/profiles"
  ver="$(cat "$src/VERSION" 2>/dev/null || echo '0.0.0-unknown')"
  echo "  $layer: version $ver"
  run rm -rf "$DEST/$layer"
  run cp -R "$src" "$DEST/$layer"
done

if [ "$DRY" -eq 1 ]; then
  echo "  [dry] .vendor.lock was not written"
  exit 0
fi

{
  echo "# GENERATED by bin/vendor.sh — edits will be overwritten."
  echo "# The layer versions this machine uses, and the checksums of their files."
  echo "# Compared by platform/bin/check-vendor.sh: a mismatch means the layer"
  echo "# was edited in place, and the next update will lose that edit."
  echo "platform_version=$(cat "$ROOT/platform/VERSION")"
  echo "profile_version=$(cat "$ROOT/profiles/VERSION")"
  echo "---"
  manifest "$DEST/platform" platform
  manifest "$DEST/profile" profile
} > "$DEST/.vendor.lock"

echo "  .vendor.lock: $(grep -c '^[0-9a-f]' "$DEST/.vendor.lock") files"
echo "Done. Verify with: cd $DEST && ./host-setup --check"
