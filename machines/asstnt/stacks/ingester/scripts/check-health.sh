#!/usr/bin/env bash

# Проверяет результат, а не механизм.
#
# Конвейер, переставший разбирать встречи, снаружи неотличим от конвейера,
# которому нечего разбирать: контейнер жив, логи молчат, таймеры зелёные.
# Поэтому смотрим на следы работы — когда последняя работа завершилась, нет ли
# мёртвых, есть ли доступ к моделям, не растёт ли отложенная очередь без меры.
#
# Работает без root, ничего не меняет, ненулевой код = есть о чём сообщить.
# Оповещение вешает сам юнит строкой OnFailure, менять тут ничего не нужно.

set -uo pipefail

CONTAINER="${Ingester_Container:-ingester}"

if ! docker ps --format '{{.Names}}' | grep -qx "$CONTAINER"; then
  echo "контейнер $CONTAINER не запущен" >&2
  exit 2
fi

docker exec "$CONTAINER" node src/cli/health.js
