#!/usr/bin/env bash

# Жив ли стек ingester — для `./scripts/stack.sh --check`.
#
# Контракт: без root, ничего не меняет, укладывается в 10 секунд, код 0 — стек
# отвечает, ненулевой — нет, первая строка вывода становится причиной в отчёте.
#
# Спрашивает ровно то же, что и часовой таймер стека (check-health.sh): следы
# работы конвейера, а не факт живости контейнера. Дублировать логику не нужно —
# нужна другая дисциплина вызова: таймер будит машину раз в час и шлёт
# оповещение, а --check отвечает человеку здесь и сейчас.
#
# Вывод обрезается первой строкой: у check-health.sh он подробный, а в отчёте
# --check строка на стек.

set -uo pipefail

DIR0="$( cd -P "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"

out="$("$DIR0/check-health.sh" 2>&1)" || {
  rc=$?
  printf '%s\n' "$out" | sed -n '1p' >&2
  exit "$rc"
}
exit 0
