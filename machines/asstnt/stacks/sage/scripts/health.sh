#!/usr/bin/env bash

# Жив ли стек sage — с точки зрения того, кто открывает сайт.
#
# Зовёт `./scripts/stack.sh --check` по включённым стекам. Контракт: без root,
# ничего не меняет, укладывается в 10 секунд, код 0 — стек отвечает, ненулевой
# — нет, и первая строка вывода становится причиной в отчёте.
#
# Проверяется весь путь целиком: nginx → vhost → upstream → приложение.
# Остальные блоки --check смотрят на части этого пути по отдельности
# (контейнер запущен, upstream резолвится, vhost включён) и каждая по
# отдельности может быть зелёной, когда домен уже не отвечает.
#
# --resolve, а не Host-заголовок: с заголовком curl отправит SNI по адресу
# (127.0.0.1), nginx выберет сервер по умолчанию и ответит редиректом, а
# проверка покажет зелёное, не дойдя до sage вовсе.
#
# Порт берём с петли, а не снаружи: проверка должна работать и на машине без
# выхода в интернет, и не зависеть от DNS. Внешнюю проверку делает
# stacks/sage/external/health-watch.sh — это другая задача.

set -uo pipefail

HOST="api.sage.filinn.ai"
TIMEOUT=5

code=$(curl -s -o /dev/null -w '%{http_code}' --max-time "$TIMEOUT" \
       --resolve "$HOST:443:127.0.0.1" "https://$HOST/health" 2>/dev/null)

case "$code" in
  200) exit 0 ;;
  000) echo "$HOST не отвечает на петле: nginx не слушает или не обслуживает этот домен" >&2; exit 1 ;;
  *)   echo "$HOST вернул HTTP $code вместо 200" >&2; exit 1 ;;
esac
